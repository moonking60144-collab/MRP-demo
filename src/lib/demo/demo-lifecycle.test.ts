test('PUT 原方法、存單轉單去重、工令建立與多個 consumer 的權威狀態一致', async () => {
  const runId = latestRun().id, part = 'XA-PRODUCT-001-R1';
  const uncertain = state().suggestions.find((row) => row.mrpRunId === runId && row.transferStatus === 'unknown' && state().transfers.some((plan) => plan.mrpRunId === runId && plan.partVersion === row.partVersion && plan.planSequence === row.planSequence))!;
  const inspected = await query('POST', `fg-monthly/${uncertain.partVersion}/suggestions/reconcile`, { runId, planSequence: uncertain.planSequence, action: 'inspect' });
  assert.equal(inspected.status, 200); assert.equal(inspected.body.inspection.matchStatus, 'single_match');
  assert.equal(typeof inspected.body.inspection.candidates[0].suggestedQty, 'number');
  assert.doesNotThrow(() => inspected.body.inspection.candidates[0].suggestedQty.toLocaleString());
  assert.equal((await query('PUT', 'fg-monthly/ignored-customers', { codes: [' xa ', 'XA'] })).status, 200);
  assert.deepEqual((await query('GET', 'fg-monthly/ignored-customers')).body.codes, ['XA']);
  await query('PUT', 'fg-monthly/ignored-customers', { codes: [] });
  const saved = await query('PATCH', `fg-monthly/${part}/suggestions`, { runId, planSequence: 1, suggestedQty: 1000, completionDate: '2026-09-30', targetStartPeriod: 1, fulfillToPeriod: 3, bufferPct: 0.1 });
  assert.equal(saved.status, 200); assert.equal(saved.body.useManualQty, true);
  const transferred = await query('PATCH', `fg-monthly/${part}/suggestions`, { runId, planSequence: 1, isTransferred: true, returnSuggestions: true });
  assert.equal(transferred.status, 200); assert.equal(transferred.body.isTransferred, true);
  const again = await query('PATCH', `fg-monthly/${part}/suggestions`, { runId, planSequence: 1, isTransferred: true });
  assert.equal(again.body.transferId, transferred.body.transferId);
  const transfers = (await query('GET', `production-plans?runId=${runId}`)).body.transfers;
  assert.equal(transfers.filter((row: { partVersion: string; planSequence: number }) => row.partVersion === part && row.planSequence === 1).length, 1);
  const id = transferred.body.transferId;
  generatedTransferId = id;
  const created = await query('POST', `production-plans/${id}/work-orders`);
  assert.equal(created.status, 202); assert.equal(created.body.workOrderStatus, 'queued');
  assert.equal((await query('POST', `production-plans/${id}/work-orders`)).status, 409);
  await new Promise((resolve) => setTimeout(resolve, 350));
  assert.equal((await query('GET', `production-plans/${id}/work-orders`)).body.workOrderStatus, 'succeeded');
  await query('PATCH', 'fg-monthly/XA-PRODUCT-003-R1/suggestions', { runId, planSequence: 1, suggestedQty: 2000, completionDate: '2026-09-30' });
  const other = await query('PATCH', 'fg-monthly/XA-PRODUCT-003-R1/suggestions', { runId, planSequence: 1, isTransferred: true });
  assert.equal((await query('POST', `production-plans/${other.body.transferId}/work-orders`)).status, 202);
  await new Promise((resolve) => setTimeout(resolve, 350));
  const otherArtifact = (await query('GET', `production-plans/${other.body.transferId}/work-orders`)).body.workOrderResponse;
  const newBom = otherArtifact.bom.find((row: { componentNo: string }) => row.componentNo === 'DEMO-B-003');
  assert.equal(newBom.remainingUsage, 2000); assert.equal(newBom.netIssuedQty, 0); assert.equal(newBom.reservedQty, 0);
  const plans = (await query('GET', `plan-management?runId=${runId}`)).body.items;
  assert.equal(plans.find((row: { transferId: number }) => row.transferId === id).workOrderStatus, 'succeeded');
  assert.equal((await query('PATCH', `fg-monthly/${part}/suggestions`, { runId: 1, planSequence: 1, suggestedQty: 100 })).status, 409);
});
test('主檔更新不改快照；暫停、停止、續算與晚到結果不污染 latest', async () => {
  const oldId = latestRun().id, before = JSON.stringify(dataset(oldId));
  const data = dataset(oldId), inv = data.source.inventory.find((row) => row.erpPartNo === 'DEMO-W-001')!;
  const current = state().leadTimes['DEMO-W-001'] ?? Number(inv.purchaseLeadWeeks);
  const changed = await query('PATCH', `component-weekly/DEMO-W-001/purchase-lead-time?runId=${oldId}&mrpType=W`, { ragicRecordId: inv.ragicRecordId, expectedPurchaseLeadWeeks: current, expectedConfigured: true, purchaseLeadWeeks: current + 1 });
  assert.equal(changed.status, 200); assert.equal(JSON.stringify(dataset(oldId)), before);
  assert.equal((await query('PATCH', 'component-weekly/DEMO-W-001/purchase-lead-time?runId=1&mrpType=W', { ragicRecordId: inv.ragicRecordId, expectedPurchaseLeadWeeks: current + 1, expectedConfigured: true, purchaseLeadWeeks: current + 2 })).status, 409);
  const started = await query('POST', 'runs', {}), id = started.body.runId;
  assert.equal(started.status, 202);
  assert.equal((await query('POST', 'runs', {})).status, 409);
  assert.equal((await query('PATCH', `component-weekly/DEMO-W-001/purchase-lead-time?runId=${oldId}&mrpType=W`, { ragicRecordId: inv.ragicRecordId, expectedPurchaseLeadWeeks: current + 1, expectedConfigured: true, purchaseLeadWeeks: current + 2 })).status, 409);
  assert.equal((await query('POST', `runs/${id}/signal`, { action: 'pause' })).status, 200);
  await new Promise((resolve) => setTimeout(resolve, 300));
  assert.equal((await query('GET', 'runs/active')).body.runId, id);
  await query('POST', `runs/${id}/signal`, { action: 'stop' });
  await new Promise((resolve) => setTimeout(resolve, 250));
  assert.equal(latestRun().id, oldId); assert.equal(state().snapshots[String(id)], undefined);
  assert.equal((await query('POST', `runs/${id}/resume`)).status, 202);
  for (let attempt = 0; attempt < 30 && state().runs.find((run) => run.id === id)?.status === 'calculating'; attempt++) await new Promise((resolve) => setTimeout(resolve, 100));
  assert.equal(latestRun().id, id);
  assert.equal(dataset(id).cw.find((row) => row.materialPartNo === 'DEMO-W-001')?.purchaseLeadWeeks, current + 1);
  assert.equal(JSON.stringify(dataset(oldId)), before);
  const generatedNumber = `DEMO-GENERATED-WO-${generatedTransferId}`;
  assert.equal(dataset(id).source.work_orders.find((row) => row.woNumber === generatedNumber)?.woQty, 1000);
  const generatedBom = dataset(id).source.work_order_bom.filter((row) => row.woNumber === generatedNumber);
  assert.equal(generatedBom.length, 3);
  assert.equal(generatedBom.find((row) => row.componentNo === 'DEMO-B-001')?.remainingUsage, 1000);
  const expected = dataset(id).source.work_order_bom.filter((row) => row.componentNo === 'DEMO-B-001' && row.issuedQtyState !== 'unknown').reduce((sum, row) => sum + Number(row.remainingUsage ?? row.minUsage), 0);
  assert.equal(dataset(id).cwPeriods['DEMO-B-001'].reduce((sum, row) => sum + Number(row.usage), 0), expected);
  const suggestionsBefore = JSON.stringify(state().suggestions);
  assert.equal((await query('PATCH', 'fg-monthly/XA-PRODUCT-001-R1/suggestions', { runId: oldId, planSequence: 1, suggestedQty: 99 })).status, 409);
  assert.equal((await query('PATCH', 'fg-monthly/XA-PRODUCT-001-R1/suggestions', { planSequence: 1, suggestedQty: 99 })).status, 409, 'RUN_ORIGIN_REQUIRED');
  assert.equal(JSON.stringify(state().suggestions), suggestionsBefore);
  const previous = structuredClone(state().suggestions.filter((row) => row.mrpRunId === oldId));
  const target = state().suggestions.find((row) => row.mrpRunId === id && row.partVersion === 'XA-PRODUCT-001-R1')!;
  assert.equal((await query('POST', 'fg-monthly/XA-PRODUCT-001-R1/suggestions/reconcile', { runId: id, planSequence: target.planSequence, action: 'confirm_not_created' })).status, 200);
  assert.deepEqual(state().suggestions.filter((row) => row.mrpRunId === oldId), previous);
  assert.equal(state().suggestions.find((row) => row.mrpRunId === id && row.partVersion === target.partVersion && row.planSequence === target.planSequence)?.transferStatus, 'failed');
});
