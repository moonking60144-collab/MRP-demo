test('歷史清單、原版 adapters、Run 身分反例與唯讀拒絕', async () => {
  const list = await query('GET', 'archive/runs?page=2');
  assert.equal(list.status, 200); assert.equal(list.body.total, 64); assert.equal(list.body.runs.length, 14);
  for (const run of [archiveRuns[0], archiveRuns[63]]) {
    const fg = await query('GET', `archive/runs/${run.id}/fg-report`);
    const adapted = adaptArchiveFgReport(fg.body);
    assert.equal(adapted.items.length, 48); assert.equal(fg.body.run.sourceRunId, run.sourceRunId);
    const aggregate = await query('GET', `archive/runs/${run.id}/fg-report?aggregated=true`);
    assert.equal(adaptArchiveFgReport(aggregate.body).items.length, 24);
    const weekly = await query('GET', `archive/runs/${run.id}/weekly-report?kind=component&mrpType=B`);
    assert.equal(adaptArchiveWeeklyReport(weekly.body).componentItems.length, 12);
    const sales = await query('GET', `archive/runs/${run.id}/weekly-report?kind=sales`);
    assert.equal(adaptArchiveWeeklyReport(sales.body).salesItems.length, 48);
    fg.body.periods[0].mrp_run_id = '999';
    assert.throws(() => adaptArchiveFgReport(fg.body), /不一致/);
    assert.equal((await query('POST', `archive/runs/${run.id}`)).status, 405);
  }
  const run = archiveRuns[0];
  assert.equal((await query('GET', `fg-material-reminders?archiveId=${run.id}&runId=3&targets=[]`)).status, 409);
  assert.equal((await query('PATCH', `fg-monthly/XA-PRODUCT-001-R1/suggestions?archiveId=${run.id}`, { planSequence: 1, suggestedQty: 100 })).status, 405);
});
