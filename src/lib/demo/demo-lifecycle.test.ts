async function query(method: 'GET' | 'POST' | 'PATCH' | 'PUT', path: string, body?: unknown) {
  const url = new URL(`http://127.0.0.1:3142/demo-api/${path}`);
  const request = new NextRequest(url, { method, ...(body !== undefined ? { body: JSON.stringify(body), headers: { 'Content-Type': 'application/json' } } : {}) });
  const response = await ({ GET, POST, PATCH, PUT }[method])(request, { params: Promise.resolve({ path: url.pathname.slice('/demo-api/'.length).split('/') }) });
  return { status: response.status, body: await response.json() };
}
